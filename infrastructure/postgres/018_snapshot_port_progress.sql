-- ============================================================================
-- AgentOS · 018 · 可恢复点必须带走**注入的智能实现**的进度
-- ----------------------------------------------------------------------------
-- 起因（空洞 241，M86 闭合）
--
--   `RunSnapshot` 的 docstring 写着它是"一次可恢复点的**全部**数据"。
--   那句话在它被写下的那天是真的，但它悄悄过期了 ——
--   因为"全部"里只包含了 **Runtime 自己的**内存状态：
--
--       steps / consecutive_denials / steps_of_run / spent / trace / pending_*
--
--   而 `assemble_runtime_stack` 还注入进来两个 **Intelligence** 实现
--   （Planner / DecisionEngine）。它们可以无状态，也可以自己记着
--   "我走到第几步了" —— 后者是合法的，`demo_stack.py` 就是这么写的：
--
--       # 每个 Run 一个 DecisionEngine：它是**有状态的**（第几步了），
--       # 跨 Run 共享会让第二个 Run 直接 FINISH。
--
--   ★ 注释承认了它是有状态的，而那句承诺只管住了"跨 Run"，
--     管不住**同一 Run 的一次恢复**。
--
-- ----------------------------------------------------------------------------
-- 后果（probe86.py 实测，不是推演）
--
--   正常路径    第 1 次 decide → LLM_CALL     第 2 次 → FINISH
--   恢复之后    新引擎第 1 次 → LLM_CALL      ← ★ 又调了一次模型
--
--   同一个 Run、同一份 State、同一段代码，两个引擎给出两个答案。
--   而**没有任何东西会发现这件事** —— 这正是它比崩溃更坏的地方。
--
--   调模型要花钱、要在外部世界的账上留痕。**静默重来一次不等于没发生。**
--   一条已经写过外部世界的 Run 被"恢复"成再来一遍，是双写不是恢复。
--
-- ----------------------------------------------------------------------------
-- 为什么是一列 JSONB，而不是拆成两个具名列
--
--   这一列装的是**Port 自述的进度**，形状由各实现自己决定
--   （计数器 / 元组 / 版本串都行）。Runtime 刻意**不解释**它，
--   只做一件事：恢复时比一次（`loop._assert_port_progress_matches`）。
--
--   拆成 planner_progress / decision_engine_progress 两列，等于让
--   Runtime 的 schema 认识"有哪几个 Port"—— 而 Port 的集合是装配层
--   的事（`assembled_runtime_stack` 将来多注入一个就得多一次迁移）。
--   一个 `{"planner": …, "decision_engine": …}` 的字典让 schema 保持
--   对装配方式无知，与 R-4 的 `trace` / `spent` 是同一套做法。
--
-- ----------------------------------------------------------------------------
-- 为什么默认值就是答案（不是"为了兼容历史行"）
--
--   `DEFAULT '{}'::jsonb` 的语义是精确的：**这份快照没有带走任何进度**，
--   于是恢复时只跟"当前实现也说不出进度"相容。
--
--   历史行（018 之前落的快照）落在这一档上，而它们对应的运行环境里
--   也**确实**没有实现 ProgressBearing —— 两边一致，恢复照常。
--   一旦有人给引擎实现了 `progress()`，那些历史快照会被点名拒绝恢复，
--   而那是对的：我们无法证明它走到哪了，就不该假装能接着跑。
--
-- ----------------------------------------------------------------------------
-- 与 R-1 的分工
--
--   R-1 管的是"快照**装得下**恢复所需的东西"（run_id / state 必填，
--   挂起必须说清在等谁）。R-7 补的是同一句话里漏掉的那一半：
--
--       装下去的必须**真的是全部** —— 包括那些不在 Runtime 手里的部分。
--
--   `RunSnapshot.state` 那条既有断言（"没有 State 的快照不是退化版快照，
--   是没法恢复的快照"）是这条新判据的**先例**：宁可构造失败，
--   也不要让它在恢复时变成一个看不出来的空壳。
-- ============================================================================

-- ============================================================================
-- 与 009 同款：**裸 ADD COLUMN**，不写 `IF NOT EXISTS`。
--
--   009 的注释把理由写死了："迁移是**只增不改**的" ——
--   每份迁移只跑一次，由账本表 `agentos_schema_migrations` 保证（O-1）。
--   既然只跑一次，"已经存在怎么办"就是一个**不会发生的问题**，
--   而 `IF NOT EXISTS` 会引入 sqlite 不认的语法（单测用替身建库）
--   —— 那等于为了防一个不会发生的事，把一半测试打死。
-- ============================================================================

ALTER TABLE run_snapshots ADD COLUMN progress JSONB NOT NULL DEFAULT '{}'::jsonb;

-- 装下去的东西必须是**对象**（上面那个字典），不是数组 / 标量。
-- 写成 CHECK 而不是只靠 Python 侧，理由与 016 完全同款：
-- 裸 INSERT、psql 里的一次手工修数、另一个还没升级的服务，
-- 都不经过 Python —— 而这一列的读法是 `stored.get("planner")`
-- 与 `stored.get("decision_engine")`，一个数组会让它们**静默拿到 None**，
-- 于是"对不上"被误判成"两边都没说"，恢复照常放行。
ALTER TABLE run_snapshots ADD CONSTRAINT run_snapshots_progress_is_object
    CHECK (jsonb_typeof(progress) = 'object');
