-- ============================================================================
-- AgentOS · 009 · RunSnapshot 补"在等哪条子 Run"
-- ----------------------------------------------------------------------------
-- 背景：R-1 的原话是"挂起必须带着你在等谁"，但它的实现把"等谁"
--       写死成了 `pending_approval_id` —— 因为写它的时候只有一种挂起原因。
--
--       M25 引入 `CHILD_AGENT` / `CHILD_SKILL` 之后，这句话开始**误伤**：
--       为子 Run 而挂起的 Run 一旦被快照，就撞上
--
--           is_gated and not pending_approval_id → InvariantViolation
--
--       即"它连一份快照都落不下来"。而落不下快照 = 恢复不了（R-1）。
--
--       所以补这一列，并把断言放宽成"审批 id 或子 Run id 必须有一个"
--       （R-6，见 §64）。
--
-- 为什么是 ALTER 而不是改 004：
--   迁移是**只增不改**的。004 已经在跑的系统里执行过一次，
--   改它等于让"已经迁移到哪一步"失去答案。
-- ============================================================================

ALTER TABLE run_snapshots ADD COLUMN pending_child_id TEXT;
