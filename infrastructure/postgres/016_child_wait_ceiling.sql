-- ============================================================================
-- AgentOS · 016 · 一次派生的等待上限**不得长于平台上限**
-- ----------------------------------------------------------------------------
-- 起因（空洞 230，M39 那一轮登记，M43 闭合）
--
--   015 给每一次派生都钉了一个等待上限（D-18），但那个上限只有一个来源：
--   **登记处的全局默认**（30 分钟）。于是"这次派生该等多久"这个问题
--   唯一的落点是一个**部署级**配置 —— 这是一次基数错配：
--
--       这个问句的主语是"这次派生"（child_runs : wait_until = 1 : 1）
--       而它的答案住在"这次部署"（registry : wait_timeout = 1 : 1）
--
--   代价是双向的，而且两个方向都很贵：
--
--     · 想给一条深度研究型子 Agent 两小时 → 必须把全局调到两小时
--       → **所有**派生都跟着多等两小时 → 一条真死掉的子 Run 让它的父 Run
--         多挂两小时（015 / 空洞 229 刚治好的东西被稀释掉）
--     · 不调 → 那条两小时的子 Agent 在第 30 分钟被判"等不到"，
--       而它其实马上就要回来了 —— 平台**制造了一个谎言**
--       （PR-19："等不到"与"它没干成"是两件事）
--
-- ----------------------------------------------------------------------------
-- 为什么"开入口"必须同时"定边界"（D-32）
--
--   等待上限属于**控制**（Harness），不属于**决策**（Intelligence）：
--
--     · "这次委派大概要跑多久"确实是决策的一部分 —— 只有 Intelligence
--       知道它派出的是个两小时的深度研究还是两秒钟的查表
--     · 但"父 Run 什么时候不再等"是**控制** —— 它决定一条挂住的 Run
--       能挂多久，而"挂住的父 Run"正是 M37~M42 连续四轮在治的形状
--
--   所以入口开出来的时候，裁决权必须留在 Harness：
--   `ChildRunRequest` 与登记处各裁决一次，越界是**点名拒绝**，
--   不是静默截断、也不是静默回退到默认。
--
--      静默截断 → 父 Run 在一个**没人同意过的时刻**被判"等不到"
--      静默回退 → "我要等两小时"变成"等 30 分钟就被判等不到"，
--                 而调用方拿到的是一个**正常的返回值** —— 一次被吞掉的拒绝
--
-- ----------------------------------------------------------------------------
-- 为什么这条边界是**物理的**（D-33 的第二道）
--
--   Python 侧的裁决（`delegation.freeze_wait_deadline`）是第一道：
--   它抛的是会**说话**的错误（"谁要求了多少、上限是多少"），
--   而数据库的 `IntegrityError` 不会 —— 它只说某个约束被违反了（PR-19）。
--
--   但它不能是唯一一道。理由与 D-1 完全同款：
--
--       D-1 的物理保证是 UNIQUE(parent_execution_id)，不是"先查一下"
--
--   裸 INSERT、`psql` 里的一次手工修数、另一个还没升级的服务，
--   都不经过 Python。没有这一行，`wait_until = '2099-01-01'` 就是合法的
--   —— 而那正是这一轮在测试夹具里**真的发现过**的写法：
--   三处集成夹具用"等到 2099 年"来表示"不会到期"。
--   015 允许它；016 不允许。
--
-- ----------------------------------------------------------------------------
-- 为什么它不是配置
--
--   平台上限是"一条父 Run 最多能被挂多久"，它是一道**平台级**承诺。
--   做成配置就会出现"数据库说什么"与"代码说什么"分岔：
--   同一个 `wait_until` 在这个部署合法、在那个部署非法。
--
--   部署想更严格 → 用登记处的 `max_wait_timeout`（只许更小，不许更大，
--   见 `_resolve_ceiling`）。想更宽松 → 走迁移，改这一句 `interval`，
--   并且同步改 `delegation.MAX_CHILD_WAIT_TIMEOUT` —— 两边不一致会红。
-- ============================================================================

-- 与 `delegation.MAX_CHILD_WAIT_TIMEOUT` 必须相等。
-- `tests/unit/test_child_wait_budget.py` 用正则把这一句抠出来对齐，
-- 与 015 的回填是同一条规矩（改一边忘另一边会红）。
ALTER TABLE child_runs ADD CONSTRAINT child_runs_wait_deadline_ceiling
    CHECK (wait_until <= spawned_at + interval '6 hours');
